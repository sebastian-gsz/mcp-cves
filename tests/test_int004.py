class TestParsersLockfiles(unittest.TestCase):
    def test_pnpm(self):
        deps = intel_osv._parse_pnpm_lock(PNPM_MINI)
        self.assertIn(("acorn", "8.11.0"), deps)
        self.assertIn(("@babel/core", "7.23.0"), deps)  # scope con @ resuelto por el último @
        self.assertEqual(len(deps), 2)  # snapshots: fuera

    def test_package_lock_v3(self):
        deps = intel_osv._parse_package_lock(json.dumps(PACKAGE_LOCK_V3))
        self.assertIn(("lodash", "4.17.21"), deps)
        self.assertIn(("@scope/pkg", "1.2.3"), deps)
        self.assertIn(("deep", "0.0.9"), deps)  # node_modules anidados

    def test_package_lock_legacy_v1(self):
        deps = intel_osv._parse_package_lock(json.dumps(PACKAGE_LOCK_V1))
        self.assertIn(("lodash", "4.17.21"), deps)
        self.assertIn(("nested", "2.0.0"), deps)  # transitivos del legacy

    def test_yarn(self):
        deps = intel_osv._parse_yarn_lock(YARN_MINI)
        self.assertIn(("@babel/core", "7.23.0"), deps)  # múltiples rangos → una versión
        self.assertIn(("lodash", "4.17.21"), deps)

    def test_poetry_uv(self):
        self.assertIn(("requests", "2.31.0"), intel_osv._parse_poetry_lock(POETRY_MINI))
        deps_uv = intel_osv._parse_uv_lock(UV_MINI)
        self.assertIn(("requests", "2.31.0"), deps_uv)
        self.assertNotIn(("miproyecto", "0.1.0"), deps_uv)  # el propio proyecto fuera

    def test_deteccion_incluye_lockfiles(self):
        with tempfile.TemporaryDirectory() as d:
            with open(os.path.join(d, "pnpm-lock.yaml"), "w") as f:
                f.write(PNPM_MINI)
            with open(os.path.join(d, "requirements.txt"), "w") as f:
                f.write("x==1.0\n")
            nombres = {n for n, _ in intel_osv.detectar_manifiestos(d)}
        self.assertEqual(nombres, {"pnpm-lock.yaml", "requirements.txt"})


class TestQueryBatch(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self._env = mock.patch.dict(os.environ, {"CVESCANNER_DB": os.path.join(self._tmp.name, "c.sqlite3")})
        self._env.start()
        self.addCleanup(self._env.stop)
        self.addCleanup(self._tmp.cleanup)

    @staticmethod
    def _batch_resp(vulns_por_indice):
        r = mock.Mock()
        r.raise_for_status = lambda: None
        r.json = lambda: {"results": [{"vulns": v} for v in vulns_por_indice]}
        return r

    def test_lote_una_peticion(self):
        vuln = [{"id": "GHSA-1", "aliases": ["CVE-2021-44228"], "summary": "RCE",
                 "database_specific": {"severity": "critical"}}]
        pares = [("PyPI", "a", "1.0"), ("PyPI", "b", "2.0"), ("npm", "c", "3.0")]
        with mock.patch("intel_osv.requests.post", return_value=self._batch_resp([vuln, [], []])) as m:
            out = intel_osv.consultar_osv_batch(pares)
        m.assert_called_once()  # 3 pares → 1 sola petición
        self.assertEqual(out[("PyPI", "a", "1.0")][0]["cve_id"], "CVE-2021-44228")
        self.assertEqual(out[("npm", "c", "3.0")], [])

    def test_chunking_240_entradas(self):
        pares = [("npm", f"pkg{i}", "1.0.0") for i in range(240)]
        r = self._batch_resp([[]] * 100)
        with mock.patch("intel_osv.requests.post", return_value=r) as m:
            out = intel_osv.consultar_osv_batch(pares, chunk=100)
        self.assertEqual(m.call_count, 3)  # 240/100 → 3 peticiones
        self.assertEqual(len(out), 240)

    def test_fallo_lote_cae_a_individual(self):
        pares = [("PyPI", "x", "1.0")]
        individual = [{"id": "GHSA-2", "aliases": [], "summary": "", "database_specific": {}}]
        resp_ok = mock.Mock()
        resp_ok.raise_for_status = lambda: None
        resp_ok.json = lambda: {"vulns": individual}
        with mock.patch("intel_osv.requests.post",
                        side_effect=[Exception("batch caído"), resp_ok]) as m:
            out = intel_osv.consultar_osv_batch(pares)
        self.assertEqual(m.call_count, 2)  # batch falla → individual
        self.assertEqual(out[("PyPI", "x", "1.0")][0]["osv_id"], "GHSA-2")

    def test_cache_respeta_segunda_llamada(self):
        pares = [("PyPI", "z", "9.9")]
        with mock.patch("intel_osv.requests.post", return_value=self._batch_resp([[]])) as m:
            intel_osv.consultar_osv_batch(pares)
            intel_osv.consultar_osv_batch(pares)
        m.assert_called_once()


class TestNucleoLockfiles(unittest.TestCase):
    """El caso de la auditoría externa: proyecto con pnpm-lock → árbol entero auditado."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self._env = mock.patch.dict(os.environ, {"CVESCANNER_DB": os.path.join(self._tmp.name, "c.sqlite3")})
        self._env.start()
        self.addCleanup(self._env.stop)
        self.addCleanup(self._tmp.cleanup)

    def test_pnpm_lock_audita_transitivos(self):
        with tempfile.TemporaryDirectory() as proyecto:
            with open(os.path.join(proyecto, "pnpm-lock.yaml"), "w") as f:
                f.write(PNPM_MINI)
            vuln = [{"id": "GHSA-x", "aliases": ["CVE-2023-44487"], "summary": "RCE",
                     "database_specific": {"severity": "high"}}]
            with mock.patch("intel_osv.consultar_osv_batch",
                            return_value={("npm", "acorn", "8.11.0"): vuln,
                                          ("npm", "@babel/core", "7.23.0"): []}), \
                 mock.patch("intel_kev.load_kev_set", return_value=set()), \
                 mock.patch("intel_exploit.armas_para_cves", return_value={}):
                hallazgos = nucleo.escanear_dependencias(proyecto)
        self.assertEqual(len(hallazgos), 1)
        h = hallazgos[0]
        self.assertEqual((h["os"], h["software"], h["version"], h["banner"]),
                         ("npm", "acorn", "8.11.0", "pnpm-lock.yaml"))  # transitivo del lockfile

    def test_caso_235_versiones_en_3_lotes(self):
        with tempfile.TemporaryDirectory() as proyecto:
            lineas = ["lockfileVersion: '9.0'", "", "packages:", ""]
            for i in range(235):
                lineas += [f"  'pkg{i}@1.0.{i}':", "    resolution: {integrity: x}", ""]
            with open(os.path.join(proyecto, "pnpm-lock.yaml"), "w") as f:
                f.write("\n".join(lineas))
            # forma PARSEADA (la que devuelve consultar_osv_batch), no el crudo de OSV
            vuln = [{"cve_id": "CVE-2023-44487", "osv_id": "GHSA-caso", "resumen": "RCE",
                     "cvss": 7.5, "url": "https://osv.dev/vulnerability/GHSA-caso"}]
            resultados = {("npm", f"pkg{i}", f"1.0.{i}"): (vuln if i == 0 else []) for i in range(235)}
            with mock.patch("intel_osv.consultar_osv_batch", return_value=resultados), \
                 mock.patch("intel_kev.load_kev_set", return_value=set()), \
                 mock.patch("intel_exploit.armas_para_cves", return_value={}) as armas:
                hallazgos = nucleo.escanear_dependencias(proyecto)
            self.assertEqual(armas.call_count, 1)  # pipeline ejecutado sobre las 235
            self.assertEqual(len(hallazgos), 1)    # solo pkg0 traía vulnerabilidad


